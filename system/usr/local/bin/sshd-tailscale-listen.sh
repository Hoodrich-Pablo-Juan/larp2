#!/bin/sh
# Render the OpenSSH ListenAddress from the current Tailscale IPv4 address.
# Keeps the tailnet-only SSH listener correct if the node's Tailscale IP changes.
#
# tailscaled may not have an IP yet moments after boot (After=tailscaled only
# orders the unit start), so retry for up to ~60s before failing. If the IP
# never shows up, keep the last generated ListenAddress rather than leaving
# sshd dead, but fail loudly on a first-ever boot with no state at all.
set -eu
out=/etc/ssh/sshd_config.d/21-tailscale-listen.conf
ip=""
for i in $(seq 1 30); do
    ip=$(/usr/bin/tailscale ip -4 2>/dev/null | head -n1)
    [ -n "$ip" ] && break
    sleep 2
done
if [ -z "$ip" ]; then
    if [ -f "$out" ]; then
        echo "sshd: tailscale has no IPv4 address yet; keeping last known ListenAddress" >&2
        exit 0
    fi
    echo "sshd: tailscale has no IPv4 address yet; cannot bind tailnet SSH" >&2
    exit 1
fi
if ! grep -Fq "ListenAddress ${ip}:2222" "$out" 2>/dev/null; then
    printf "# Generated by sshd-tailscale-listen.sh -- do not edit by hand.\nListenAddress %s:2222\n" "$ip" >"$out.tmp"
    chmod 0644 "$out.tmp"
    mv "$out.tmp" "$out"
fi
